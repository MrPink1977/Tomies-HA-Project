@app.get("/health")
def health():
    ldr_ok = False
    try:
        r = requests.get(f"{LDR_URL}/auth/login", timeout=5)
        ldr_ok = r.status_code < 500
    except Exception:
        pass
    return {"status": "ok", "ldr_reachable": ldr_ok, "ldr_url": LDR_URL, "ha_url": HA_URL}


@app.post("/research")
def research(req: ResearchRequest, background_tasks: BackgroundTasks):
    title = req.title or req.query
    log.info("Research request: query=%r title=%r iterations=%d", req.query, title, req.iterations)
    background_tasks.add_task(run_research, req.query, title, req.iterations)
    return {
        "status": "started",
        "query": req.query,
        "title": title,
        "iterations": req.iterations,
        "message": "Research started. HA webhook will fire when complete.",
    }


@app.get("/reports")
def list_reports():
    try:
        files = sorted(os.listdir(REPORT_DIR), reverse=True)
        return {"reports": files}
    except Exception:
        return {"reports": []}
